import { readFileSync, writeFileSync } from "node:fs";

const rustRawString = (content) => {
  let delimiter = "#";
  while (content.includes('"' + delimiter)) delimiter += "#";
  return `r${delimiter}"${content}"${delimiter}`;
};

const writeIfChanged = (name, source) => {
  const ffiPath = new URL(`../../src/Gopurs/${name}`, import.meta.url);
  let previous;
  try {
    previous = readFileSync(ffiPath, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }

  // Preserve timestamps when unchanged, for both native and JS bootstrap builds.
  if (previous !== source) writeFileSync(ffiPath, source);
};

// Resolve from this script so npm --prefix and direct invocation use the same
// source. The generated FFI is embedded by Spago/esbuild, with no runtime I/O.
const runtimePath = new URL("../../runtime/runtime.go", import.meta.url);
const runtime = readFileSync(runtimePath, "utf8");
const header =
  "// Generated by tools/build/embed-runtime.mjs from runtime/runtime.go.\n" +
  "// Edit the Go source, then run npm run build.\n";
const sources = [
  ["Runtime/Source.js", header + `export const runtimeGoCode = ${JSON.stringify(runtime)};\n`],
  [
    "Runtime/Source.go",
    header + "package Gopurs_Runtime_Source\n\n" + `var RuntimeGoCode = ${JSON.stringify(runtime)}\n`,
  ],
  [
    "Runtime/Source.rs",
    header +
      `pub fn Gopurs_Runtime_Source_runtimeGoCode() -> String {\n` +
      `    purust_string_from_utf8(${rustRawString(runtime)})\n}\n`,
  ],
];

for (const [name, source] of sources) {
  writeIfChanged(name, source);
}

const simdSpecs = [
  ["simdAsmGoCode", "SimdAsmGoCode", "simd_asm.go"],
  ["simdGenericGoCode", "SimdGenericGoCode", "simd_generic.go"],
  ["simdArm64AsmCode", "SimdArm64AsmCode", "simd_arm64.s"],
  ["simdAmd64AsmCode", "SimdAmd64AsmCode", "simd_amd64.s"],
];
const simdEntries = simdSpecs.map(([jsName, goName, file]) => ({
  jsName,
  goName,
  content: readFileSync(new URL(`../../runtime/${file}`, import.meta.url), "utf8"),
}));
const simdHeader =
  "// Generated by tools/build/embed-runtime.mjs from runtime/simd_*.\n" +
  "// Edit the runtime SIMD sources, then run npm run build.\n";
const simdSources = [
  [
    "Runtime/Simd.js",
    simdHeader +
      simdEntries.map(({ jsName, content }) => `export const ${jsName} = ${JSON.stringify(content)};\n`).join(""),
  ],
  [
    "Runtime/Simd.go",
    simdHeader +
      "package Gopurs_Runtime_Simd\n\n" +
      simdEntries.map(({ goName, content }) => `var ${goName} = ${JSON.stringify(content)}\n`).join(""),
  ],
  [
    "Runtime/Simd.rs",
    simdHeader +
      simdEntries
        .map(
          ({ jsName, content }) =>
            `pub fn Gopurs_Runtime_Simd_${jsName}() -> String {\n` +
            `    purust_string_from_utf8(${rustRawString(content)})\n}\n`,
        )
        .join("\n"),
  ],
];

for (const [name, source] of simdSources) {
  writeIfChanged(name, source);
}
